"""
Simulation: do the website's tests behave as promised?

    python tools/coverage.py            # 1000 series per scenario
    python tools/coverage.py 300        # quicker

For series with a known true trend and realistic noise, it measures with stats.js:
  - coverage: how often the 95% confidence interval contains the true trend (should be ~95%)
  - false alarms: how often a trend-free series is called significant (should be ~5%)
The table is printed and saved to tools/VALIDATION.md.
"""
import datetime
import os
import sys

import numpy as np

from common import HERE, run_js


def ar1_noise(rng, n, phi, sd):
    e = np.zeros(n)
    e[0] = rng.normal(0, sd / np.sqrt(1 - phi ** 2)) if phi else rng.normal(0, sd)
    for k in range(1, n):
        e[k] = phi * e[k - 1] + rng.normal(0, sd)
    return e


SCENARIOS = [
    # name, points, step (years), AR(1) phi, correct for autocorrelation
    ("Yearly, 45 years, independent noise", 45, 1.0, 0.0, False),
    ("Yearly, 45 years, autocorrelated noise (r1 = 0.3)", 45, 1.0, 0.3, False),
    ("Monthly, 540 months, r1 = 0.6, no correction", 540, 1 / 12, 0.6, False),
    ("Monthly, 540 months, r1 = 0.6, corrected (what the site does)", 540, 1 / 12, 0.6, True),
]


def run(n_sims):
    rng = np.random.default_rng(14)
    rows = []
    for name, n, step, phi, corr in SCENARIOS:
        x = 1981 + (np.arange(n) + (0.5 if step < 1 else 0)) * step
        true_slope = 0.02
        cases = []
        for _ in range(n_sims):
            cases.append({"x": x, "y": true_slope * (x - 1981) + ar1_noise(rng, n, phi, 0.3), "opts": {"ar1": True} if corr else None})
        for _ in range(n_sims):
            cases.append({"x": x, "y": ar1_noise(rng, n, phi, 0.3), "opts": {"ar1": True} if corr else None})
        res = run_js(cases)
        trend, flat = res[:n_sims], res[n_sims:]
        cover = np.mean([r["ols"]["ciLow"] <= true_slope <= r["ols"]["ciHigh"] for r in trend])
        fa_mk = np.mean([r["mk"]["p"] < 0.05 for r in flat])
        fa_t = np.mean([r["ols"]["p"] < 0.05 for r in flat])
        power = np.mean([r["mk"]["p"] < 0.05 for r in trend])
        rows.append((name, cover, fa_mk, fa_t, power))
        print("%-62s coverage %5.1f%%  false alarms MK %4.1f%% t %4.1f%%  detects real trend %5.1f%%"
              % (name, cover * 100, fa_mk * 100, fa_t * 100, power * 100))
    return rows


def write_report(rows, n_sims):
    lines = [
        "# Statistics validation",
        "",
        "Generated by `tools/coverage.py` on %s with %d simulated series per row (half with a true trend of "
        "+0.2 per decade, half with none). Noise standard deviation 0.3." % (datetime.date.today().isoformat(), n_sims * 2),
        "",
        "| Scenario | 95% interval contains the true trend | False alarms, Mann-Kendall | False alarms, t-test | Real trend detected |",
        "|---|---|---|---|---|",
    ]
    for name, cover, fa_mk, fa_t, power in rows:
        lines.append("| %s | %.1f%% | %.1f%% | %.1f%% | %.1f%% |" % (name, cover * 100, fa_mk * 100, fa_t * 100, power * 100))
    lines += [
        "",
        "Targets: about 95% coverage and about 5% false alarms.",
        "",
        "- Independent yearly noise: the tests behave as promised.",
        "- Autocorrelated yearly noise makes the plain tests overconfident; the website shows a caution note when "
        "lag-1 autocorrelation is strong.",
        "- Monthly data without a correction would be badly overconfident. The website corrects monthly data for "
        "autocorrelation, which brings coverage and false alarms back near their targets.",
        "",
        "`tools/validate_stats.py` separately checks every number stats.js reports against SciPy "
        "(`linregress`, `theilslopes`, `t`, `norm`) and textbook formulas.",
        "",
    ]
    with open(os.path.join(HERE, "VALIDATION.md"), "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 1000
    write_report(run(n), n)
    print("Saved tools/VALIDATION.md")
