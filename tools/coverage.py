"""
Simulation: do the website's tests behave as promised?

    python tools/coverage.py            # 1000 series per scenario
    python tools/coverage.py 300        # quicker

For series with a known true trend and realistic noise, it measures with stats.js:
  - coverage: how often the 95% interval contains the true trend (should be ~95%)
  - false alarms: how often a trend-free series is called significant (should be ~5%)
Each is shown for the plain tests and for the memory-adjusted tests the site uses.
The table is printed and saved to tools/VALIDATION.md.
"""
import datetime
import os
import sys

import numpy as np
from scipy import stats

from common import HERE, run_js


def ar1_noise(rng, n, phi, sd):
    e = np.zeros(n)
    e[0] = rng.normal(0, sd / np.sqrt(1 - phi ** 2)) if phi else rng.normal(0, sd)
    for k in range(1, n):
        e[k] = phi * e[k - 1] + rng.normal(0, sd)
    return e


SCENARIOS = [
    # name, points, step (years), AR(1) phi
    ("Yearly, 45 years, independent noise", 45, 1.0, 0.0),
    ("Yearly, 45 years, year-to-year memory r = 0.3", 45, 1.0, 0.3),
    ("Monthly, 540 months, memory r = 0.6", 540, 1 / 12, 0.6),
]


def run(n_sims):
    rng = np.random.default_rng(14)
    rows = []
    for name, n, step, phi in SCENARIOS:
        x = 1981 + (np.arange(n) + (0.5 if step < 1 else 0)) * step
        true_slope = 0.02
        cases = [{"x": x, "y": true_slope * (x - 1981) + ar1_noise(rng, n, phi, 0.3)} for _ in range(n_sims)]
        cases += [{"x": x, "y": ar1_noise(rng, n, phi, 0.3)} for _ in range(n_sims)]
        res = run_js(cases)
        trend, flat = res[:n_sims], res[n_sims:]
        tc = stats.t.ppf(0.975, n - 2)
        plain_cover = np.mean([r["ols"]["slope"] - tc * r["ols"]["se"] <= true_slope <= r["ols"]["slope"] + tc * r["ols"]["se"] for r in trend])
        adj_cover = np.mean([r["ols"]["ciLow"] <= true_slope <= r["ols"]["ciHigh"] for r in trend])
        plain_fa = np.mean([r["mk"]["p"] < 0.05 for r in flat])
        adj_fa = np.mean([r["mk"]["pAdj"] < 0.05 for r in flat])
        power = np.mean([r["mk"]["pAdj"] < 0.05 for r in trend])
        rows.append((name, plain_cover, adj_cover, plain_fa, adj_fa, power))
        print("%-48s coverage plain %5.1f%% adjusted %5.1f%% | false alarms plain %4.1f%% adjusted %4.1f%% | real trend found %5.1f%%"
              % (name, plain_cover * 100, adj_cover * 100, plain_fa * 100, adj_fa * 100, power * 100))
    return rows


def write_report(rows, n_sims):
    lines = [
        "# Statistics validation",
        "",
        "Generated by `tools/coverage.py` on %s with %d simulated series per row (half with a true trend of "
        "+0.2 per decade, half with none), run through the website's own `stats.js`. Noise standard deviation 0.3."
        % (datetime.date.today().isoformat(), n_sims * 2),
        "",
        "| Scenario | 95% interval contains the true trend: plain | adjusted (site) | False alarms, Mann-Kendall: plain | adjusted (site) | Real trend detected (site) |",
        "|---|---|---|---|---|---|",
    ]
    for name, pc, ac, pf, af, pw in rows:
        lines.append("| %s | %.1f%% | %.1f%% | %.1f%% | %.1f%% | %.1f%% |" % (name, pc * 100, ac * 100, pf * 100, af * 100, pw * 100))
    lines += [
        "",
        "Targets: about 95% coverage and about 5% false alarms.",
        "",
        "The site adjusts both tests for year-to-year memory (lag-1 autocorrelation, effective sample size). "
        "Without that adjustment, data with memory gives intervals that are too narrow and too many false alarms; "
        "with it, both stay near their targets.",
        "",
        "`tools/validate_stats.py` separately checks every number stats.js reports against SciPy "
        "(`linregress`, `theilslopes`, `t`, `norm`) and the formulas in the Methods section.",
        "",
    ]
    with open(os.path.join(HERE, "VALIDATION.md"), "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 1000
    write_report(run(n), n)
    print("Saved tools/VALIDATION.md")
